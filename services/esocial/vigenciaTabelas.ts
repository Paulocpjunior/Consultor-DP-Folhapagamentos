const NOME: Record<TabelaVigencia, string> = { '01': 'Categoria', '03': 'Natureza', '18': 'Motivo de afastamento', '19': 'Motivo de desligamento' };
/** Substitutas conhecidas na própria tabela oficial (código encerrado → o vigente que tomou o lugar). */
const SUBSTITUTA: Partial<Record<TabelaVigencia, Record<string, string>>> = {
    '03': { '1002': '1012', '1020': '1016 e 1017', '1801': '1800' },
    '18': { '33': 'o 17 e o 18 (prorrogação da Empresa Cidadã)', '30': 'nenhum: a suspensão disciplinar saiu da Tabela 18; lance os dias como faltas no movimento' },
};
const br = (d: string) => d.split('-').reverse().join('/');

/**
 * Código fora da vigência na tabela oficial na data (AAAA-MM-DD ou AAAA-MM, o 1º dia do mês): a mensagem com a data do
 * fim (ou do início) e a substituta, quando há; null se vale. Código que a tabela não tem também é recusado.
 */
export function foraDaVigencia(tabela: TabelaVigencia, codigo: string, data: string): string | null {
    const dia = /^\d{4}-\d{2}$/.test(data) ? `${data}-01` : data;
    if (!codigo || !/^\d{4}-\d{2}-\d{2}$/.test(dia)) return null;
    const faixas = VIGENCIAS[tabela][codigo];
    const quem = `${NOME[tabela]} ${codigo} (Tabela ${tabela} do eSocial)`;
    if (!faixas) return `${quem}: não existe na tabela oficial.`;
    if (faixas.some(([ini, fim]) => ini <= dia && (!fim || fim >= dia))) return null;
    const subst = SUBSTITUTA[tabela]?.[codigo];
    const futura = faixas.every(([ini]) => ini > dia);
    if (futura) return `${quem}: só vale a partir de ${br(faixas.map(([ini]) => ini).sort()[0])}.`;
    const fim = faixas.map(([, f]) => f ?? '').sort().pop() ?? '';
    return `${quem}: encerrado em ${br(fim)} na tabela oficial${subst ? `; use ${subst}` : ''}.`;
}
